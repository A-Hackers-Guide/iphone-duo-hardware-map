"""Compare two device trees parsed by adt.py, node by node and property by property.

usage: dt_diff.py A.json "A label" B.json "B label" out.md
"""
import json
import sys

a_path, a_lab, b_path, b_lab, out = sys.argv[1:6]


def flatten(t):
    nodes = {}

    def walk(n, path):
        nm = n['props'].get('name', {}).get('str', '?')
        nm = nm[0] if isinstance(nm, list) else nm
        path = f'{path}/{nm}' if path is not None else ''
        nodes[path or '/'] = n['props']
        for c in n['children']:
            walk(c, path)
    walk(t, None)
    return nodes


def show(p):
    if p is None:
        return '—'
    if 'str' in p and not (p['len'] == 4 and isinstance(p['str'], str) and len(p['str']) < 3):
        s = p['str']
        return ', '.join(s) if isinstance(s, list) else s
    if 'u32' in p:
        return f'{p["u32"]:#x}'
    if p['len'] == 0:
        return '(empty)'
    return f'{p["len"]} B {p["hex"][:48]}{"…" if p["len"] > 24 else ""}'


def comp(props):
    c = props.get('compatible')
    return show(c) if c else ''


A, B = flatten(json.load(open(a_path))), flatten(json.load(open(b_path)))
onlyA = sorted(set(A) - set(B))
onlyB = sorted(set(B) - set(A))
both = sorted(set(A) & set(B))
IGN = {'AAPL,phandle', 'interrupt-parent'}

L = [f'# Device tree diff: {a_lab} vs {b_lab}', '',
     f'Generated by `tools/dt_diff.py`. {a_lab}: {len(A)} nodes. {b_lab}: {len(B)} nodes. '
     f'{len(both)} paths in both, {len(onlyA)} only in {a_lab}, {len(onlyB)} only in {b_lab}. '
     'Paths are compared by name, so a renamed node shows up on both sides. phandles and interrupt parents are ignored '
     'because they are renumbered between trees. **[DT]**', '',
     f'## Only in {a_lab} ({len(onlyA)})', '', '| Node | compatible |', '|---|---|']
L += [f'| `{p}` | {comp(A[p])} |' for p in onlyA]
L += ['', f'## Only in {b_lab} ({len(onlyB)})', '', '| Node | compatible |', '|---|---|']
L += [f'| `{p}` | {comp(B[p])} |' for p in onlyB]
L += ['', '## Nodes in both, with different properties', '']
changed = 0
for p in both:
    ka, kb = set(A[p]) - IGN, set(B[p]) - IGN
    rows = []
    for k in sorted(ka | kb):
        va, vb = A[p].get(k), B[p].get(k)
        if va is not None and vb is not None and va['hex'] == vb['hex']:
            continue
        rows.append(f'| `{k}` | {show(va).replace("|", "/")} | {show(vb).replace("|", "/")} |')
    if rows:
        changed += 1
        L += [f'### `{p}`', '', f'| Property | {a_lab} | {b_lab} |', '|---|---|---|'] + rows + ['']
L.insert(3, f'{changed} shared nodes differ in at least one property.')
open(out, 'w').write('\n'.join(L) + '\n')
print(out, len(onlyA), len(onlyB), changed)
