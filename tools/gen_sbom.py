"""Firmware software bill of materials: every `@(#)PROGRAM:<name> PROJECT:<project>-<version>` tag, RTKit/pitayaOS
build string and other version banner embedded in each firmware payload, grouped by image. Each tag marks one
program or library linked into that co-processor's firmware. Writes reference/maps/firmware-sbom.md.

usage: gen_sbom.py <dir containing Firmware/> reference/maps/firmware-sbom.md
"""
import os
import re
import subprocess
import sys
import tempfile

root, out = sys.argv[1:3]
TAG = re.compile(rb'@\(#\)PROGRAM:([\x21-\x7e]+)\s+PROJECT:([\x21-\x7e]+)')
BANNER = re.compile(rb'(RTKit_[\w.\-~]+|pitayaOS[\w.\-]*|AppleFirmwareKit-[\d.]+|iBoot-[\d.]+|mBoot-[\d.]+|SPTM-[\d.]+|'
                    rb'TrustedExecutionMonitor[\w.\-]*|AppleStorageFirmware-[\w.~]+|AppleDCP-[\w.~]+|AppleMTPFirmware[\w.\-~]+)')

files = []
for dp, dn, fn in os.walk(os.path.join(root, 'Firmware')):
    for f in fn:
        if f.endswith(('.im4p', '.bin', '.sefw', '.vnlfw')):
            files.append(os.path.join(dp, f))
files.sort()
tmp = tempfile.mkdtemp(prefix='sbom-')
L = ['# Firmware software bill of materials', '',
     'Every `@(#)PROGRAM:… PROJECT:…` tag and build banner inside each firmware payload of the iPhone19,4 iOS 27.2 restore image. '
     'Apple\'s build system stamps each program and library with such a tag, so this lists what software, at what project version, '
     'is linked into each co-processor\'s firmware. Encrypted payloads (SEP OS) show nothing. Generated by `tools/gen_sbom.py`. **[FW]**', '']
summary = []
for f in files:
    rel = os.path.relpath(f, root)
    data = None
    if f.endswith('.im4p'):
        o = os.path.join(tmp, 'p')
        subprocess.run(['ipsw', 'img4', 'im4p', 'extract', f, '-o', o], capture_output=True)
        if os.path.exists(o):
            data = open(o, 'rb').read()
            os.remove(o)
    if data is None:
        data = open(f, 'rb').read()
    tags = sorted({(a.decode('latin-1'), b.decode('latin-1')) for a, b in TAG.findall(data)})
    banners = sorted({m.decode('latin-1') for m in BANNER.findall(data)})
    if not tags and not banners:
        continue
    summary.append((rel, len(tags)))
    L += ['', f'## `{rel}`', '', f'[Firmware page](../firmware/{rel.replace("/", "__")}.md). {len(tags)} program tags.', '']
    if banners:
        L += ['Build banners: ' + ', '.join(f'`{b}`' for b in banners[:12]), '']
    if tags:
        L += ['| Program | Project |', '|---|---|'] + [f'| `{a}` | `{b}` |' for a, b in tags]
L.insert(4, f'{len(summary)} images carry tags or banners; {sum(n for _, n in summary)} program tags in total.')
open(out, 'w').write('\n'.join(L) + '\n')
print(len(summary), sum(n for _, n in summary))
